"""把 probe.json 中存活的节点导出成 new-api 可用的代理清单
用法: python tools/export_proxies.py [--out-dir out] [--out proxies.txt] [--host 127.0.0.1]
输出: 每行 socks5://host:port, # 开头为注释
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', default=os.path.join(ROOT, 'out'))
    ap.add_argument('--out', default=None)
    ap.add_argument('--host', default='127.0.0.1')
    a = ap.parse_args()

    ports = json.load(open(os.path.join(a.out_dir, 'ports.json')))
    probe_path = os.path.join(a.out_dir, 'probe.json')
    probe = {}
    if os.path.exists(probe_path):
        probe = {r['id']: r for r in json.load(open(probe_path, encoding='utf-8'))}
    dst = a.out or os.path.join(a.out_dir, 'proxies.txt')
    lines = ['# generated by tools/export_proxies.py — 只含 probe.json 判定存活的节点']
    n = 0
    for nid, port in ports.items():
        st = probe.get(nid)
        if st is None:
            continue                      # 未测活的节点不导出(宁可少, 不可错)
        if not st.get('alive'):
            continue
        lines.append('socks5://%s:%d' % (a.host, port))
        n += 1
    open(dst, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('%s  %d 条代理 (来自 %d 个端口, 已测活 %d)' % (dst, n, len(ports), len(probe)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
